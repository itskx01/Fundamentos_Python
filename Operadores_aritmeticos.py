# Operadores aritmeticos

a = 5
b = 10

# suma 
suma = a + b  
print (suma)

# resta
resta = a - b  
print (resta)

# division
division = a / b  
print (division)

# division entera
division_entera = a // b  
print (division_entera)

# multiplicacion
multiplicacion = a * b  
print (multiplicacion)

# modulo
residuo = a % b  
print (residuo)

# exponenciacion
exponenciacion = a ** b  
print (exponenciacion)



